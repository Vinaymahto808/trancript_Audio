"""Run the fast Audio Transcriber locally on port 8000 (default).

hf_space/app.py is the Space payload generated by build_space.py and hardcodes
the Space port (7860). This wrapper executes the same file locally with the
port rewritten, without touching the payload itself.

Usage:
    python run_local.py          # port 8000
    python run_local.py 4001     # custom port
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPACE = ROOT / "hf_space"
APP = SPACE / "app.py"
PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8000

source = APP.read_text(encoding="utf-8")
source = source.replace("server_port=7860", f"server_port={PORT}")

exec(compile(source, str(APP), "exec"), {"__name__": "__main__", "__file__": str(APP)})
